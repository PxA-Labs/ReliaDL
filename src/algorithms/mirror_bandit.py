"""
EXP3 multi-armed bandit mirror router for ReliaDL.

Chooses which mirror to issue the next range request to when a file is
available from several CDN edges or replicas. The problem is adversarial rather
than merely noisy: an edge node's throughput depends on other tenants' load,
routing changes and cache state, none of which are stationary and none of which
are observable. EXP3 is the right tool because it assumes nothing about the
reward distribution — no independence, no stationarity, not even that rewards
are generated by a process rather than chosen to spite us.

Only the reward of the mirror actually used is observed; the counterfactual
throughput of the mirrors not chosen is unknowable. That is what makes this a
bandit rather than a prediction problem, and it is the constraint the algorithm
is built around:

    p_{m,t} = (1 - eta) * w_{m,t} / sum_j w_{j,t}  +  eta / M
    r_hat   = r / p_{m,t}
    w_{m,t+1} = w_{m,t} * exp(eta * r_hat / M)

The uniform eta/M floor does two jobs, and the second is easy to overlook.
It keeps every mirror under occasional test so a recovered edge can be
rediscovered, and it bounds every selection probability away from zero, which
is what makes the importance-weighted estimate r/p finite. Dividing by a
probability that could reach zero would be unbounded; the floor is what makes
the estimator well defined rather than merely convenient.

Dividing by the selection probability is what keeps the estimate unbiased. A
mirror chosen a tenth of the time has its observed reward scaled up tenfold, so
in expectation each arm's accumulated estimate reflects what it would have
earned had it been played every round. Without that correction the algorithm
would conflate "rarely chosen" with "low reward" and never escape its first
impression.

Numerical representation
------------------------
Weights are held as logarithms, which is a requirement rather than a
refinement. The exponent of a single update is bounded by 1 — since
r <= 1 and p >= eta/M give r_hat <= M/eta, so eta * r_hat / M <= 1 — but that
bound is per round, and it accumulates. A weight can therefore grow like e^T
over T rounds, and a long download makes tens of thousands of range requests;
e^10000 is not representable. In log space the same growth is linear and the
weights are rescaled after every update so the largest is exactly 1, which
leaves the selection distribution untouched (it depends only on weight ratios)
while keeping every exponential in range.

Tracking a moving target
------------------------
Classic EXP3 has vanishing regret against the best *fixed* arm in hindsight,
which is the wrong target here: over a long transfer the best mirror changes.
Accumulated weights make the algorithm progressively more confident and
correspondingly slower to react, so an edge that was fastest for the first ten
thousand chunks keeps its lead long after it has degraded.

The optional decay mixes each weight back toward the mean every round,

    w_m <- (1 - alpha) * w_m + (alpha / M) * sum_j w_j

which caps how much evidence any arm can hoard and gives the router a finite
memory. This is the EXP3.S variant, and it is what converts a bandit that
converges into one that tracks. With alpha = 0 the behaviour is exactly classic
EXP3.

Choosing the decay is a real tradeoff, so it was measured rather than guessed.
Regret against the best mirror in hindsight, three mirrors, eta = 0.1, averaged
over 24 seeded trials of 5000 rounds, under a stationary schedule, an abrupt
mid-transfer failover, and a gradual drift. The reward stream is seeded
independently of the router's own sampler; sharing a seed makes the two draw
identical values in lockstep and couples each reward to the arm that draw
selected, which quietly favours whichever mirror sits first in the cumulative
distribution:

    decay     stationary   switching   drifting   worst
    0                217        1709        771    1709
    0.0002           246         378        222     378
    0.0005           279         390        235     390
    0.001            333         426        256     426
    0.002            420         494        311     494
    0.004            578         633        397     633

Classic EXP3 wins the stationary column and is unusable everywhere else: having
committed to the leading mirror it cannot recover when that mirror degrades,
which is the single behaviour this router exists to avoid. Any small positive
decay cuts worst-case regret by more than four times for about a tenth more
regret in the stationary case, which is a trade worth making for a transfer
whose mirrors are not under our control.

The optimum sat at alpha = 0.0002, which is 1/T for the 5000-round horizon
measured. That is not a coincidence — it is the EXP3.S guidance alpha ~ 1/T —
and it was confirmed to hold at other horizons, alpha = 1/T minimizing
worst-case regret at T = 1000, 2000 and 10000 alike. ``decay_for_horizon``
applies that relationship for callers who know how many range requests a
transfer will make.
"""

